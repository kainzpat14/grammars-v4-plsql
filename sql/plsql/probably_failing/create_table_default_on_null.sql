-- CREATE TABLE with DEFAULT ON NULL clause
-- Tests various forms of DEFAULT ON NULL for columns

-- Basic DEFAULT ON NULL
CREATE TABLE employees (
    emp_id NUMBER PRIMARY KEY,
    emp_name VARCHAR2(100),
    salary NUMBER DEFAULT ON NULL 0,
    department VARCHAR2(50) DEFAULT ON NULL 'UNASSIGNED'
);

-- DEFAULT ON NULL with expressions
CREATE TABLE orders (
    order_id NUMBER PRIMARY KEY,
    order_date DATE DEFAULT ON NULL SYSDATE,
    status VARCHAR2(20) DEFAULT ON NULL 'PENDING',
    total_amount NUMBER DEFAULT ON NULL 0.00
);

-- DEFAULT ON NULL with GENERATED ... AS IDENTITY
CREATE TABLE products (
    product_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(100) NOT NULL,
    price NUMBER DEFAULT ON NULL 0,
    created_date DATE DEFAULT ON NULL SYSDATE
);

-- Multiple columns with DEFAULT ON NULL
CREATE TABLE customer_orders (
    order_id NUMBER PRIMARY KEY,
    customer_id NUMBER,
    order_date DATE DEFAULT ON NULL CURRENT_DATE,
    ship_date DATE DEFAULT ON NULL CURRENT_DATE + 7,
    discount_percent NUMBER DEFAULT ON NULL 0,
    tax_rate NUMBER DEFAULT ON NULL 0.10,
    notes VARCHAR2(500) DEFAULT ON NULL 'No notes'
);

-- DEFAULT ON NULL with function calls
CREATE TABLE audit_log (
    log_id NUMBER PRIMARY KEY,
    log_timestamp TIMESTAMP DEFAULT ON NULL SYSTIMESTAMP,
    user_id VARCHAR2(50) DEFAULT ON NULL USER,
    session_id NUMBER DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSIONID'),
    action_type VARCHAR2(50) DEFAULT ON NULL 'UNKNOWN'
);

-- DEFAULT ON NULL with sequences (legacy style)
CREATE TABLE legacy_table (
    id NUMBER DEFAULT ON NULL seq_legacy.NEXTVAL PRIMARY KEY,
    code VARCHAR2(20) DEFAULT ON NULL 'N/A',
    value NUMBER DEFAULT ON NULL -1
);

-- Combination of DEFAULT and DEFAULT ON NULL
CREATE TABLE mixed_defaults (
    id NUMBER PRIMARY KEY,
    col1 VARCHAR2(50) DEFAULT 'DEFAULT_VALUE',
    col2 VARCHAR2(50) DEFAULT ON NULL 'NULL_VALUE',
    col3 NUMBER DEFAULT 100,
    col4 NUMBER DEFAULT ON NULL 0
);

-- DEFAULT ON NULL with INVISIBLE columns
CREATE TABLE hidden_defaults (
    id NUMBER PRIMARY KEY,
    visible_col VARCHAR2(50),
    hidden_col VARCHAR2(50) DEFAULT ON NULL 'HIDDEN' INVISIBLE,
    calculated_col NUMBER GENERATED ALWAYS AS (id * 2) VIRTUAL
);
